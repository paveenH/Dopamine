#!/usr/bin/env python3
"""pv7 Stage-2-only ablation: instruction x OPTIONS row rotation.

WHAT THIS IS
------------
A Stage-2 MECHANISM DIAGNOSTIC on the frozen state bank. It reuses the
rationales already generated by the P1b arm (`pv7_p1b_eval.json`) verbatim and
ONLY re-scores the candidates. No Stage 1 generation happens here.

It exists because three independent observations pointed at Stage 2 rather than
at Stage 1 expression quality:

  * P1 -> P1b lifted policy parse rate 60.7% -> 100% and cut grounding errors,
    yet Button-A coverage moved only ~6pp (McNemar p=0.77, n_discordant=12).
  * P1 vs P2 likewise did not move it (p=1.0, n=17).
  * In the P1b scores, Button A carries a centered log-prob of +3.00 while the
    row-position effect spans only ~2.16.

Underpowered individually ("not detected", NOT "Stage 2 is independent of
Stage 1" -- that would be accepting the null), but jointly they justify
spending the cheap Stage-2 pass rather than iterating on Stage 1 wording.

THE CONFOUND THIS RESOLVES
--------------------------
In the observational P1b data, label and row position are PARTIALLY decoupled
already -- the bank holds 12 distinct `arm_order`s, and Button A sits in row 1
in only 54/120 states. So they are separable in principle, but the design is
UNBALANCED (A is in row 4 just 6 times), making both fixed effects biased.

Rotating the OPTIONS table through all K cyclic orders puts every letter in
every row position exactly once per state, which turns that observational
imbalance into a balanced within-state design.

FROZEN DESIGN DECISIONS (settled before any of this ran)
--------------------------------------------------------
1. Rotation moves ROWS ONLY. The letter stays bound to arm identity, because
   the letter IS the arm's name. A `Button C` that appears in a different row
   under a different rotation is the intervention, not a bug.

2. The rationale is NEVER rewritten or re-ordered. It is frozen Stage 1
   evidence; editing it would make this something other than a Stage-2
   ablation. A consequence is deliberate: a rationale naming `Button C` points
   at different row positions across rotations, and that is exactly what
   separates label effect from row-position effect.

3. `S_maskpolicy` uses S0's action instruction. Pairing a removed Policy line
   with "Follow the Policy above" would demand adherence to a policy that is
   not there -- a self-contradicting cell, not a control.

4. Real arm probabilities, the true best arm, and reward are never read here.
   Selection among interfaces must not be fitted to outcomes (the states were
   sampled from alpha=0 pv6 trajectories, so outcome-based selection would fit
   the prompt to its own history).

SCOPE LIMIT -- READ BEFORE REUSING
----------------------------------
Stage 1 sees the ORIGINAL OPTIONS order; only Stage 2 rotates. So this answers
"given an identical rationale, how sensitive is Stage 2 to label, to row
position, and to the Policy text?" -- it is NOT a drop-in interface for a full
Bandit trajectory. If rotation is ever adopted for real episodes, Stage 1 and
Stage 2 within one run MUST share a single fixed order.

Analysis units follow the pv7 convention: per-state-type tables keep all 120
slots; POOLED statistics deduplicate on `state_fingerprint` and report n=107.

Usage
-----
    python3.10 eval_pv7_stage2_ablation.py --dry_run          # no GPU
    python3.10 eval_pv7_stage2_ablation.py --source <p1b.json>
    python3.10 eval_pv7_stage2_ablation.py --report <out.json>
"""

from __future__ import annotations

import argparse
import json
import math
import statistics as st
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

import bandit_reference as br
import bandit_pv7 as p7
import eval_pv7_frozen_states as ev

BANK = Path(__file__).with_name("bandit_pv7_frozen_states.json")
SOURCE_DEFAULT = "pv7_p1b_eval.json"
SOURCE_ARM = p7.PROMPT_P1B

# ── instruction cells ────────────────────────────────────────────────────────
# S0 is pv7's frozen wording, reproduced from bandit_pv7.build_action_prompt so
# the baseline cell is byte-identical to the stored P1b run (asserted at load).
S0 = "s0_baseline"
S1 = "s1_follow_policy"
SMASK = "s_maskpolicy"
INSTRUCTIONS = (S0, S1, SMASK)

_INSTRUCTION_TEXT = {
    S0: "Now select one button to maximize total reward.",
    # Names no button and supplies no strategy -- it only asks Stage 2 to use
    # the model's OWN Policy line. Anchor and candidates are untouched.
    S1: "Follow the Policy above and select one button.",
    SMASK: "Now select one button to maximize total reward.",   # = S0, per (3)
}


def instruction_text(instruction: str) -> str:
    if instruction not in _INSTRUCTION_TEXT:
        raise ValueError(f"unknown instruction cell {instruction!r}")
    return _INSTRUCTION_TEXT[instruction]


# ── rationale handling ───────────────────────────────────────────────────────

def analysis_text(instruction: str, clean: str) -> str:
    """What goes under MODEL ANALYSIS. Never re-ordered, never rewritten."""
    if instruction == SMASK:
        return p7.strip_policy_line(clean)
    return clean


# ── rotation ─────────────────────────────────────────────────────────────────

def rotations(arm_order: list[str]) -> list[list[str]]:
    """All K cyclic rotations, so each letter visits each row exactly once.

    Cyclic (not all K! permutations) keeps the cost at K per state while still
    balancing the letter x row-position table, which is the only thing the
    fixed-effect estimates need.
    """
    k = len(arm_order)
    return [arm_order[i:] + arm_order[:i] for i in range(k)]


def build_stage2_prompt(instruction: str, snap: dict, env: br.Environment,
                        display_order: list[str], clean: str) -> str:
    """pv7 Stage 2 prompt with a swapped OPTIONS row order + a swapped
    instruction line. Everything else -- state arithmetic, MODEL ANALYSIS text,
    the `Choose Button: ` anchor -- is pv7's."""
    history = [(h["arm"], h["reward"]) for h in snap["history"]]
    state = p7.render_state(display_order, history, snap["round_idx"], env,
                            prompt_variant=SOURCE_ARM)
    body = analysis_text(instruction, clean)
    analysis = f"Evidence: {body}" if body else "Evidence:"
    prompt = (f"{state}\n\nMODEL ANALYSIS\n{analysis}\n\n"
              f"{instruction_text(instruction)}\n{p7.ACTION_ANCHOR}")
    p7._assert_single_trailing_space(prompt, p7.ACTION_ANCHOR)
    return prompt


def assert_s0_identity(snap, env, clean, stored_prompt_len: int | None) -> None:
    """S0 at rotation 0 must reproduce pv7's own Stage 2 prompt byte for byte.

    This is the negative control on the whole rebuild: if the baseline cell
    drifts from `build_action_prompt`, every contrast is measured against the
    wrong reference.
    """
    order = snap["arm_order"]
    history = [(h["arm"], h["reward"]) for h in snap["history"]]
    canonical = p7.build_action_prompt(order, history, snap["round_idx"], env,
                                       clean, prompt_variant=SOURCE_ARM)
    mine = build_stage2_prompt(S0, snap, env, order, clean)
    if mine != canonical:
        raise AssertionError(
            "S0 rotation-0 prompt does not match pv7.build_action_prompt; the "
            "baseline cell has drifted and no contrast in this file is valid")


# ── scoring ──────────────────────────────────────────────────────────────────

def score_prompt(vc, tokenizer, prompt: str, env: br.Environment) -> dict:
    """Per-candidate summed log-prob. ID-level concatenation only.

    Candidates are scored as independent batch rows, so there is no
    "first candidate in the list" ordering effect -- the only ordering under
    test is the visual row order inside the OPTIONS table.
    """
    import numpy as np
    import torch

    sfx = p7.candidate_suffixes(env)
    labels = [p7.candidate_arm(s) for s in sfx]
    # Fails closed on tail != 220, on a candidate that is not a single expected
    # token, and on BPE re-merging if the sequence were built as a string.
    p7.audit_id_level_continuation(tokenizer, prompt, sfx)
    tok_ids = [tokenizer.encode(s, add_special_tokens=False) for s in sfx]
    per_tok = vc.regenerate_logits_teacher_forcing(
        prompts=[prompt] * len(sfx), answer_token_ids=tok_ids,
        diff_matrices=None)
    scores = {}
    for lab, ids, lg in zip(labels, tok_ids, per_tok):
        lp = 0.0
        for k, tid in enumerate(ids):
            row = torch.from_numpy(np.asarray(lg[k], dtype=np.float32))
            lp += float(torch.log_softmax(row, dim=-1)[tid])
        scores[lab] = lp
    return scores


# ── the run ──────────────────────────────────────────────────────────────────

def load_source(path: Path) -> dict[str, dict]:
    """Frozen P1b rationales keyed by state fingerprint."""
    doc = json.loads(path.read_text())
    if SOURCE_ARM not in doc.get("rows", {}):
        raise SystemExit(
            f"{path} has arms {list(doc.get('rows', {}))}; this ablation reuses "
            f"the {SOURCE_ARM!r} rationales and cannot synthesise them")
    rows = doc["rows"][SOURCE_ARM]
    empty = sum(1 for r in rows if not (r.get("rationale_raw") or "").strip())
    if empty == len(rows):
        raise SystemExit(
            f"{path} holds {len(rows)} rows but every rationale is empty -- "
            "that is a --dry_run artefact, not a real generation run")
    if empty:
        print(f"  note: {empty}/{len(rows)} source rationales are empty",
              file=sys.stderr)
    return {r["state_fingerprint"]: r for r in rows}


def run(vc, tokenizer, bank, env, source, instructions, dry_run):
    rows = []
    total = len(bank["states"]) * len(instructions) * env.k
    done = 0
    for snap in bank["states"]:
        src = source.get(state_key(snap))
        if src is None:
            raise SystemExit(
                f"no stored rationale for {snap['state_id']}; the source run "
                "and the state bank disagree")
        clean = src["rationale_clean"]
        assert_s0_identity(snap, env, clean, None)

        for instruction in instructions:
            for rot_idx, order in enumerate(rotations(snap["arm_order"])):
                prompt = build_stage2_prompt(instruction, snap, env, order,
                                             clean)
                t0 = time.time()
                if dry_run:
                    scores, elapsed = {}, 0.0
                else:
                    scores = score_prompt(vc, tokenizer, prompt, env)
                    elapsed = time.time() - t0

                row = {
                    "state_id": snap["state_id"],
                    "state_fingerprint": snap["state_fingerprint"],
                    "state_type": snap["state_type"],
                    "seed": snap["seed"],
                    "round_idx": snap["round_idx"],
                    "instruction": instruction,
                    "rotation": rot_idx,
                    "display_order": order,
                    "source_arm": SOURCE_ARM,
                    # Stored so a re-read never has to re-derive what Stage 2
                    # actually saw; the mask cell differs from the source.
                    "analysis_text": analysis_text(instruction, clean),
                    "policy": ev.policy_flags(
                        clean, max(scores, key=scores.get) if scores else None),
                    "score_s": round(elapsed, 4),
                }
                if scores:
                    chosen = max(scores, key=scores.get)
                    row["scores"] = scores
                    row["choice"] = ev.choice_diag(scores, order, chosen)
                rows.append(row)
                done += 1
                if not dry_run and done % 100 == 0:
                    print(f"  {done}/{total}", flush=True)
    return rows


def state_key(snap: dict) -> str:
    return snap["state_fingerprint"]


# ── analysis ─────────────────────────────────────────────────────────────────

def dedup_pooled(rows: list[dict]) -> list[dict]:
    """Pooled stats deduplicate on fingerprint (n=107), per the pv7 convention.

    Kept separate from the per-state-type view (n=120) because one history can
    legitimately answer a different diagnostic question under two state types.
    """
    seen = set()
    out = []
    for r in rows:
        key = (r["state_fingerprint"], r["instruction"], r["rotation"])
        if key in seen:
            continue
        seen.add(key)
        out.append(r)
    return out


def _mean(xs):
    return st.mean(xs) if xs else float("nan")


def centered_effects(rows, key):
    """Centered log-prob by `key`, which is what a fixed effect estimates.

    Centering within a state removes that state's overall scale, so the numbers
    are comparable across states with very different evidence strength.
    """
    acc = defaultdict(list)
    for r in rows:
        if "scores" not in r:
            continue
        m = _mean(list(r["scores"].values()))
        for lab, v in r["scores"].items():
            k = lab if key == "label" else r["display_order"].index(lab) + 1
            acc[k].append(v - m)
    return {k: _mean(v) for k, v in sorted(acc.items(), key=lambda kv: str(kv[0]))}


def mcnemar(pairs):
    """Exact binomial McNemar. Returns (b, c, p) with b/c the discordant counts."""
    b = sum(1 for a, x in pairs if a and not x)
    c = sum(1 for a, x in pairs if x and not a)
    n = b + c
    if n == 0:
        return b, c, 1.0
    k = min(b, c)
    tail = sum(math.comb(n, i) for i in range(k + 1)) / (2 ** n)
    return b, c, min(1.0, 2 * tail)


def report(doc):
    rows = doc["rows"]
    pooled = dedup_pooled(rows)
    scored = [r for r in pooled if "scores" in r]
    if not scored:
        print("no scored rows (dry run?)")
        return

    n_states = len({r["state_fingerprint"] for r in scored})
    print(f"\npv7 Stage-2 ablation -- pooled n={n_states} unique states "
          f"(per-type view would be {len({r['state_id'] for r in rows})} slots)")
    print("Rationales are frozen P1b output; Stage 1 was not re-run.")

    instructions = [i for i in INSTRUCTIONS
                    if any(r["instruction"] == i for r in scored)]

    # 1. instruction x label, instruction x row position
    for key, title in (("label", "instruction x LABEL"),
                       ("position", "instruction x ROW POSITION")):
        print(f"\n{title} (centered log-prob)")
        cells = {i: centered_effects(
            [r for r in scored if r["instruction"] == i], key)
            for i in instructions}
        keys = sorted({k for c in cells.values() for k in c}, key=str)
        print(f"  {'':<20}" + "".join(f"{str(k):>12}" for k in keys))
        for i in instructions:
            print(f"  {i:<20}"
                  + "".join(f"{cells[i].get(k, float('nan')):>12.2f}"
                            for k in keys))

    # 2. choice distribution
    print("\nchoice share by label / by row position")
    for i in instructions:
        sub = [r for r in scored if r["instruction"] == i]
        lab = Counter(r["choice"]["chosen_label"] for r in sub)
        pos = Counter(r["choice"]["chosen_position"] for r in sub)
        n = len(sub)
        print(f"  {i:<20} label " + " ".join(
            f"{k.split()[-1]}:{v / n:.1%}" for k, v in sorted(lab.items()))
            + "   row " + " ".join(
            f"{k}:{v / n:.1%}" for k, v in sorted(pos.items())))

    # 3. policy adherence, overall and on non-A policies
    print("\naction-follows-policy (policy_first_clause, clear stance)")
    for i in instructions:
        sub = [r for r in scored if r["instruction"] == i
               and r["policy"]["policy_target_source"] == "policy_first_clause"
               and r["policy"]["stance_is_clear"]
               and r["policy"]["action_follows_policy"] is not None]
        follow = [r for r in sub if r["policy"]["action_follows_policy"]]
        nonA = [r for r in sub if r["policy"]["policy_target"] != "Button A"]
        nonA_overridden_by_A = [
            r for r in nonA if r["choice"]["chosen_label"] == "Button A"]
        print(f"  {i:<20} follow {len(follow)}/{len(sub)}"
              f" = {len(follow) / len(sub):.1%}" if sub else
              f"  {i:<20} (no parseable policies)")
        if nonA:
            print(f"  {'':<20}   non-A policy overridden by A: "
                  f"{len(nonA_overridden_by_A)}/{len(nonA)}"
                  f" = {len(nonA_overridden_by_A) / len(nonA):.1%}")

    # 4. per-target-label follow rate (C was the weakest in P1b)
    print("\nfollow rate by policy target label")
    targets = sorted({r["policy"]["policy_target"] for r in scored
                      if r["policy"]["policy_target"]})
    print(f"  {'':<20}" + "".join(f"{t.split()[-1]:>12}" for t in targets))
    for i in instructions:
        cells = []
        for t in targets:
            sub = [r for r in scored if r["instruction"] == i
                   and r["policy"]["policy_target"] == t
                   and r["policy"]["action_follows_policy"] is not None]
            f = sum(1 for r in sub if r["policy"]["action_follows_policy"])
            cells.append(f"{f / len(sub):.1%}" if sub else "-")
        print(f"  {i:<20}" + "".join(f"{c:>12}" for c in cells))

    # 5. paired contrasts, matched on (state, rotation)
    print("\npaired contrasts (matched on state x rotation)")
    for a, b, note in ((S0, S1, "does asking for the Policy help?"),
                       (SMASK, S0, "what does the Policy text itself add?")):
        idx = {}
        for r in scored:
            if r["instruction"] in (a, b):
                idx.setdefault((r["state_fingerprint"], r["rotation"]), {})[
                    r["instruction"]] = r
        pairs = [(v[a], v[b]) for v in idx.values() if a in v and b in v]
        if not pairs:
            continue
        chose_A = [(x["choice"]["chosen_label"] == "Button A",
                    y["choice"]["chosen_label"] == "Button A")
                   for x, y in pairs]
        bb, cc, p = mcnemar(chose_A)
        pa = sum(1 for x, _ in chose_A if x) / len(chose_A)
        pb = sum(1 for _, y in chose_A if y) / len(chose_A)
        print(f"  {a} -> {b}  ({note})")
        print(f"    A-share {pa:.1%} -> {pb:.1%}   n={len(pairs)}  "
              f"discordant {bb}/{cc}  McNemar p={p:.4f}")
        dm = [y["choice"]["margin"] - x["choice"]["margin"] for x, y in pairs]
        de = [y["choice"]["norm_entropy"] - x["choice"]["norm_entropy"]
              for x, y in pairs]
        print(f"    mean d(margin) {_mean(dm):+.3f}   "
              f"mean d(norm_entropy) {_mean(de):+.3f}")
        if len(pairs) < 60 or bb + cc < 25:
            print("    UNDERPOWERED: report as 'not detected', never as "
                  "'no effect'.")

    print("\nReminder: this is a Stage-2 diagnostic. Stage 1 saw the original")
    print("OPTIONS order, so rotation here is NOT a validated full-episode")
    print("interface -- a real run must share one fixed order across stages.")
    print("No true-best-arm or reward metric is computed, by design.")


# ── main ─────────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default=SOURCE_DEFAULT,
                    help="P1b result JSON whose rationales are reused verbatim")
    ap.add_argument("--out", default="pv7_stage2_ablation.json")
    ap.add_argument("--model_dir", default="meta-llama/Llama-3.1-8B-Instruct")
    ap.add_argument("--model", default="llama3")
    ap.add_argument("--size", default="8B")
    ap.add_argument("--environment", default="easy")
    ap.add_argument("--instructions", nargs="*", default=list(INSTRUCTIONS))
    ap.add_argument("--dry_run", action="store_true",
                    help="build and validate every prompt; no model, no GPU")
    ap.add_argument("--report", help="re-print tables from a stored result")
    ap.add_argument("--overwrite", action="store_true")
    args = ap.parse_args()

    if args.report:
        report(json.loads(Path(args.report).read_text()))
        return

    out = Path(args.out)
    if out.exists() and not args.overwrite and not args.dry_run:
        raise SystemExit(f"{out} exists; pass --overwrite or pick a new --out")

    for i in args.instructions:
        instruction_text(i)   # validate early, before loading a model

    bank = json.loads(BANK.read_text())
    env = br.get_environment(args.environment)
    source = load_source(Path(args.source))

    if args.dry_run:
        vc = tokenizer = None
        from transformers import AutoTokenizer
        try:
            tokenizer = AutoTokenizer.from_pretrained(args.model_dir)
        except Exception as exc:                                # noqa: BLE001
            print(f"  tokenizer unavailable ({exc}); skipping token audit",
                  file=sys.stderr)
    else:
        from llms import VicundaModel
        vc = VicundaModel(model_path=args.model_dir)
        tokenizer = vc.tokenizer

    # Validate every prompt up front so a token-alignment failure costs seconds,
    # not a multi-hour run.
    if tokenizer is not None:
        sfx = p7.candidate_suffixes(env)
        for snap in bank["states"][:1]:
            src = source[state_key(snap)]
            for i in args.instructions:
                for order in rotations(snap["arm_order"]):
                    p7.audit_id_level_continuation(
                        tokenizer,
                        build_stage2_prompt(i, snap, env, order,
                                            src["rationale_clean"]),
                        sfx)
        print("  token audit passed (tail 220, single-token candidates, "
              "ID-level concatenation)")

    t0 = time.time()
    rows = run(vc, tokenizer, bank, env, source, args.instructions,
               args.dry_run)
    doc = {
        "protocol": "pv7-stage2-ablation-v1",
        "state_bank_version": bank.get("version", "pv7-state-bank-v1"),
        "source_file": str(args.source),
        "source_arm": SOURCE_ARM,
        "environment": args.environment,
        "instructions": list(args.instructions),
        "rotation": "cyclic; every letter visits every row exactly once",
        "note": ("Stage-2 only. Rationales are frozen P1b text, never "
                 "re-ordered or rewritten. Stage 1 saw the ORIGINAL OPTIONS "
                 "order, so this is a mechanism diagnostic and not a "
                 "full-episode interface. No reward metric is computed."),
        "elapsed_s": round(time.time() - t0, 1),
        "rows": rows,
    }
    if not args.dry_run:
        out.write_text(json.dumps(doc, indent=1))
        print(f"wrote {out}  ({len(rows)} rows, {doc['elapsed_s']}s)")
    else:
        print(f"dry run OK: {len(rows)} prompts built and validated")
    report(doc)


if __name__ == "__main__":
    main()
